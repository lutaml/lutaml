# frozen_string_literal: true

require "spec_helper"
require "expressir"

# TODO.sota/03 part 2: property-based round-trip conformance —
# parse → format → parse is idempotent (structural signatures equal)
# and malformed input is rejected. The default run covers a fixture
# slice; EXPRESSIR_CONFORMANCE=1 runs the full corpus tiers.
# Capture metadata and resolution artifacts are not structure: source
# offsets shift with formatting, the schema header is the captured
# leading text, and ref/base_path are parent pointers.
ROUNDTRIP_IGNORED_KEYS = %w[source include_source source_offset remarks
                            remark_items untagged_remarks
                            informal_propositions ref base_path file
                            header].freeze

RSpec.describe Expressir::Express::Formatter do
  def strip(value)
    case value
    when Hash
      value.each_with_object({}) do |(key, inner), out|
        next if ROUNDTRIP_IGNORED_KEYS.include?(key.to_s)

        out[key] = strip(inner)
      end
    when Array then value.map { |inner| strip(inner) }
    else value
    end
  end

  def signatures(source)
    repository = Expressir::Express::Parser.from_exp(source)
    formatted = described_class.format(repository.schemas.first)
    reparsed = Expressir::Express::Parser.from_exp(formatted)
    [strip(repository.schemas.first.to_hash),
     strip(reparsed.schemas.first.to_hash)]
  end

  let(:samples) do
    Dir[Expressir.root_path.join("spec/fixtures/examples/*.exp")]
      .first(5)
  end

  # Finite-fragment generator over the Annex A/B productions: atoms and
  # expressions first, then the declaration forms that carry them.
  # Expressions are generated by production level (expression →
  # simple_expression → term → factor) because relational operators are
  # non-associative: only one may appear per expression.
  def generated_atom(rng, names)
    [rng.rand(0..99).to_s,
     format("%d.%d", rng.rand(0..9), rng.rand(1..9)),
     "'#{%w[a b c d e].sample(3, random: rng).join}'",
     names.sample(random: rng),
     "TRUE", "FALSE", "UNKNOWN"].sample(random: rng)
  end

  def generated_simple_expression(rng, names, depth)
    return generated_atom(rng, names) if depth <= 0

    case rng.rand(5)
    when 0 then "(#{generated_expression(rng, names, depth - 1)})"
    when 1, 2
      "#{generated_simple_expression(rng, names, depth - 1)} " \
      "#{%w[* / DIV MOD AND].sample(random: rng)} " \
      "#{generated_simple_expression(rng, names, depth - 1)}"
    when 3 then "-(#{generated_simple_expression(rng, names, depth - 1)})"
    when 4
      "#{generated_atom(rng, names)} ** #{generated_atom(rng, names)}"
    end
  end

  def generated_expression(rng, names, depth)
    return generated_simple_expression(rng, names, depth) if depth <= 0

    case rng.rand(6)
    when 0 then "(#{generated_expression(rng, names, depth - 1)})"
    when 1, 2
      "#{generated_simple_expression(rng, names, depth - 1)} " \
      "#{%w[+ - OR XOR].sample(random: rng)} " \
      "#{generated_simple_expression(rng, names, depth - 1)}"
    when 3
      "#{generated_simple_expression(rng, names, depth - 1)} " \
      "#{%w[< <= > >= = <>].sample(random: rng)} " \
      "#{generated_simple_expression(rng, names, depth - 1)}"
    when 4 then "NOT (#{generated_expression(rng, names, depth - 1)})"
    when 5
      case rng.rand(2)
      when 0
        items = Array.new(rng.rand(1..3)) { generated_atom(rng, names) }
        "[#{items.join(', ')}]"
      when 1
        "QUERY (q <* [#{generated_atom(rng, names)}] | TRUE)"
      end
    end
  end

  def generated_schema(rng, names)
    tag = rng.rand(10_000)
    expression = generated_expression(rng, names, 3)
    <<~EXP
      SCHEMA generated_#{tag};
      TYPE label_#{tag} = ENUMERATION OF (first, second, third);
      END_TYPE;
      TYPE measure_#{tag} = REAL;
      WHERE
        positive : SELF > 0.0;
      END_TYPE;
      ENTITY item_#{tag};
        name : label_#{tag};
        count : INTEGER;
        sizes : LIST [1:?] OF REAL;
      END_ENTITY;
      FUNCTION compute_#{tag}(p1 : INTEGER; p2 : REAL) : REAL;
      LOCAL
        l1 : REAL;
      END_LOCAL;
        RETURN (#{expression});
      END_FUNCTION;
      END_SCHEMA;
    EXP
  end

  it "re-parses formatter output to the same structure" do
    samples.each do |path|
      original, reformatted = signatures(File.read(path))
      expect(reformatted).to eq(original), "round trip diverged for #{path}"
    end
  end

  it "round-trips generated declarations and expressions" do
    (1..8).each do |seed|
      rng = Random.new(seed)
      source = generated_schema(rng, %w[p1 p2 l1])
      original, reformatted = signatures(source)
      expect(reformatted).to eq(original),
                             "round trip diverged for seed #{seed}:\n#{source}"
    end
  end

  it "rejects generated input with a missing terminator" do
    (1..8).each do |seed|
      rng = Random.new(seed)
      source = generated_schema(rng, %w[p1 p2 l1]).sub("END_SCHEMA;", "")
      expect { Expressir::Express::Parser.from_exp(source) }
        .to raise_error(StandardError), "seed #{seed} was accepted"
    end
  end

  it "does not format nested unary minus as a comment opener" do
    source = <<~EXP
      SCHEMA nested_unary;
      FUNCTION negate(operand : INTEGER) : INTEGER;
        RETURN (-(-operand));
      END_FUNCTION;
      END_SCHEMA;
    EXP
    original, reformatted = signatures(source)
    expect(reformatted).to eq(original)
  end

  it "rejects truncated declarations" do
    path = samples.first
    source = File.read(path)
    expect { Expressir::Express::Parser.from_exp(source[0, source.length / 2]) }
      .to raise_error(StandardError)
  end

  if ENV["EXPRESSIR_CONFORMANCE"]
    it "round-trips the full stepmod resource slice" do
      stepmod = ENV["STEPMOD_DIR"] ||
        File.expand_path("~/src/mn/iso-10303-stepmod")
      corpus = File.join(stepmod, "data/resources")
      skip "stepmod corpus not present at #{corpus}" unless Dir.exist?(corpus)

      files = Dir[File.join(corpus, "**/*.exp")]
        .select { |f| File.size(f) < 250_000 }
      checked = 0
      files.each do |path|
        original, reformatted = signatures(File.read(path))
        expect(reformatted).to eq(original),
                               "round trip diverged for #{path}"
        checked += 1
      rescue Parsanol::ParseFailed, Expressir::Express::Error::SchemaParseFailure
        next
      end
      expect(checked).to be > 200
    end
  end
end
