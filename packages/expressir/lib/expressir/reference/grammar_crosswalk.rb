# frozen_string_literal: true

require "yaml"

module Expressir
  module Reference
    # Rule-by-rule cross-walk between the parsanol grammar and the
    # ISO 10303-11 Annex A/B productions. The mapping data is generated
    # by `rake reference:crosswalk`; the spec fails when a grammar rule
    # has no row or the rendered guide is stale.
    class GrammarCrosswalk
      DATA_PATH = File.expand_path("grammar_crosswalk.yml", __dir__)
      GRAMMAR_RULE = /rule\(:(\w+)/
      PRODUCTION_STATUSES = %w[aligned decomposed].freeze

      class << self
        def data
          @data ||= YAML.load_file(DATA_PATH)
        end

        def grammar_path
          Expressir.root_path.join(data.dig("source", "grammar"))
        end

        def grammar_rules
          File.read(grammar_path).scan(GRAMMAR_RULE).flatten.uniq.sort
        end

        def rows
          data["rules"]
        end

        def annex_without_rule
          data["annex_without_rule"]
        end

        def statuses
          data["statuses"]
        end

        # Returns the list of inconsistencies; empty means in sync.
        def validate
          errors = []
          declared = rows.map { |row| row["rule"] }
          missing = grammar_rules - declared
          unknown = declared - grammar_rules
          duplicates = declared.tally.select { |_, count| count > 1 }.keys
          errors << "grammar rules without a cross-walk row: #{missing.join(', ')}" if missing.any?
          errors << "cross-walk rows without a grammar rule: #{unknown.join(', ')}" if unknown.any?
          errors << "duplicate cross-walk rows: #{duplicates.join(', ')}" if duplicates.any?

          rows.each do |row|
            status = row["status"]
            unless statuses.key?(status)
              errors << "#{row['rule']}: unknown status '#{status}'"
            end
            if PRODUCTION_STATUSES.include?(status) && !row["production"]
              errors << "#{row['rule']}: #{status} row needs a production"
            end
          end
          errors
        end

        def render_adoc
          lines = [
            "= Grammar cross-walk",
            "",
            "// Generated by `rake reference:crosswalk` from",
            "// #{data.dig('source', 'grammar')} and the Annex A snapshot.",
            "// Do not edit by hand; the reference spec fails when this file is stale.",
            "",
            "== Purpose",
            "",
            "Every parsanol grammar rule is mapped to the ISO 10303-11:2004",
            "Annex A production it implements. Divergences from the standard",
            "grammar are classified with one of these statuses:",
            "",
            *statuses.map { |name, description| "* `#{name}` — #{description}" },
            "",
            "== Rules",
            "",
            '[cols="2,3,1,4", options="header"]',
            "|===",
            "| Parsanol rule | Annex A production | Status | Note",
            "",
            *rows.map { |row| rule_row(row) },
            "|===",
            "",
            "== Annex A productions without a dedicated rule",
            "",
            "These productions are handled by supporting code rather than a",
            "grammar rule:",
            "",
            '[cols="3,1,5", options="header"]',
            "|===",
            "| Annex A production | Status | Handled by",
            "",
            *annex_without_rule.map { |row| annex_row(row) },
            "|===",
            "",
          ]
          lines.join("\n")
        end

        private

        def rule_row(row)
          note = row["literal"] ? "literal `#{row['literal']}`" : row["note"]
          "| `#{row['rule']}` | #{cell(row['production'])} | #{row['status']} | #{cell(note)}"
        end

        def annex_row(row)
          "| `#{row['production']}` | #{row['status']} | #{cell(row['note'])}"
        end

        def cell(text)
          text.to_s.gsub("|", "\\|")
        end
      end
    end
  end
end
