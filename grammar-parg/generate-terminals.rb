# frozen_string_literal: true

# Generates the keyword-terminal fragment of express.parg from the DSL's
# KEYWORDS list (lib/expressir/express/grammar/parser.rb). Each DSL rule
#   rule(:tKW) { cts(keyword_rule(KW).as(:str)).as(tKW) }
# is case-insensitive KW with a trailing identifier-character guard:
#   tKW = (ci(KW)) as tKW
# with ci() expanded per character to ("A" / "a") pairs and the guard
# !(letter / digit / "_") appended once per keyword.

KEYWORDS = %i[
  ABS ABSTRACT ACOS AGGREGATE ALIAS AND ANDOR ARRAY AS ASIN ATAN BAG BASED_ON
  BEGIN BINARY BLENGTH BOOLEAN BY CASE CONSTANT CONST_E COS DERIVE DIV ELSE
  END END_ALIAS END_CASE END_CONSTANT END_ENTITY END_FUNCTION END_IF
  END_LOCAL END_PROCEDURE END_REPEAT END_RULE END_SCHEMA
  END_SUBTYPE_CONSTRAINT END_TYPE ENTITY ENUMERATION ESCAPE EXISTS EXP
  EXTENSIBLE FALSE FIXED FOR FORMAT FROM FUNCTION GENERIC_ENTITY
  GENERIC HIBOUND HIINDEX IF IN INSERT INTEGER INVERSE LENGTH LIKE LIST LOBOUND
  LOCAL LOG LOG10 LOG2 LOGICAL LOINDEX MOD NOT NUMBER NVL ODD OF ONEOF OPTIONAL
  OR OTHERWISE PI PROCEDURE QUERY REAL REFERENCE REMOVE RENAMED REPEAT RETURN
  ROLESOF RULE SCHEMA SELECT SELF SET SIN SIZEOF SKIP SQRT STRING SUBTYPE
  SUBTYPE_CONSTRAINT SUPERTYPE TAN THEN TO TRUE TYPE TYPEOF TOTAL_OVER UNIQUE
  UNKNOWN UNTIL USE USEDIN VALUE VALUE_IN VALUE_UNIQUE VAR WITH WHERE WHILE
  XOR
].freeze

# PARG text for one case-insensitive character (literal pair or single).
def ci_char(ch)
  return "\"#{ch}\"" unless ch.match?(/[a-zA-Z]/)

  "(\"#{ch.upcase}\" / \"#{ch.downcase}\")"
end

def parg_name(sym)
  # Underscored keywords keep their underscore (BASED_ON → tBASED_ON);
  # CONST_E keeps the E; all names are valid PARG idents.
  "t#{sym}"
end

out = []
out << "# --- keyword terminals (generated by generate-terminals.rb; do not"
out << "#     hand-edit — rerun the script instead) ---"
out << "# The trailing-identifier guard: a keyword must not be followed by"
out << "# a letter, digit, or underscore (the DSL's match[a-zA-Z0-9_].absent?)."
out << "identGuard = !(%x41-5A / %x61-7A / %x30-39 / \"_\")"
KEYWORDS.each do |kw|
  body = kw.to_s.chars.map { |c| ci_char(c) }.join(" ")
  out << "#{parg_name(kw)} = #{body} identGuard as #{parg_name(kw)}"
end
puts out.join("\n")
